"""Action role: select exactly one enabled read capability.

Phase 1 exposes read capabilities only. The Action role never mints operation
identifiers, argument hashes or approvals, and it never executes a tool: it
returns a proposal that the governance gateway decides on.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import cast

from agents.context import ModelCallConfig, ModelClient, ModelMessage
from agents.idempotency import compute_args_hash, generate_operation_id
from agents.policy import PHASE1_ACTION_READ_TOOLS, WRITE_TOOL_NAMES
from agents.schemas import ActionProposal, PendingOperation, TicketState
from tools.registry import TOOL_REGISTRY
from tools.schemas import WriteToolName


def read_tool_catalogue() -> str:
    """Describe only the capabilities enabled in this phase."""
    lines = ["Enabled read capabilities (select exactly one, or none):"]
    lines.extend(
        f"- {name}: {TOOL_REGISTRY[name].description}"
        for name in PHASE1_ACTION_READ_TOOLS
    )
    return "\n".join(lines)


async def select_action(
    *,
    state: TicketState,
    system_prompt: str,
    model_client: ModelClient,
    config: ModelCallConfig,
) -> ActionProposal:
    messages = [
        ModelMessage(role="system", content=system_prompt),
        ModelMessage(
            role="user",
            content=f"User request: {state['user_query']}\n\n{read_tool_catalogue()}",
        ),
    ]
    return await model_client.complete_structured(
        messages=messages,
        output_model=ActionProposal,
        config=config,
    )


def create_pending_operation(
    proposal: ActionProposal,
    *,
    operation_id: str | None = None,
    evidence_result_ids: list[str] | None = None,
    schema_version: str = "1.0.0",
) -> PendingOperation:
    """Deterministic factory creating PendingOperation from ActionProposal.

    Invariants (architecture §6.4):
    - Validated arguments conform to tool input schema
    - operation_id is deterministically generated by code, never by the model
    - args_hash is SHA-256 of canonical arguments
    - side_effects is strictly "write"
    """
    if proposal.tool_name not in WRITE_TOOL_NAMES:
        raise ValueError(
            f"Cannot create PendingOperation for non-write tool {proposal.tool_name!r}"
        )
    evidence_ids = (
        evidence_result_ids
        if evidence_result_ids is not None
        else proposal.evidence_result_ids
    )
    op_id = operation_id or generate_operation_id()
    return PendingOperation(
        operation_id=op_id,
        tool_name=cast(WriteToolName, proposal.tool_name),
        validated_args=proposal.arguments,
        args_hash=compute_args_hash(proposal.arguments),
        side_effects="write",
        evidence_result_ids=evidence_ids,
        proposed_by="action",
        proposed_at=datetime.now(UTC),
        schema_version=schema_version,
    )
